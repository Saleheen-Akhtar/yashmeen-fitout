export function mergeWebsiteContent(remote) {
  const merge = (defaults, value) => {
    if (value === undefined || value === null) return structuredClone(defaults);
    if (Array.isArray(defaults)) return Array.isArray(value) ? value : structuredClone(defaults);
    if (defaults && typeof defaults === 'object') {
      return Object.fromEntries(Object.entries(defaults).map(([key, fallback]) => [key, merge(fallback, value[key])]));
    }
    return value;
  };
  const result = { ...remote, ...merge(DEFAULT_WEBSITE_CONTENT, remote) };
  result.services = result.services.map(service => {
    const defaults = DEFAULT_WEBSITE_CONTENT.services.find(item => item.slug === service.slug);
    return defaults ? { ...service, ...merge(defaults, service) } : service;
  });
  return result;
}

// Only public fields can leave the admin API or enter the visitor cache.
export function publicWebsiteContent(content) {
  return Object.fromEntries(Object.keys(DEFAULT_WEBSITE_CONTENT)
    .filter(key => !['crmTasks', 'calendarEvents'].includes(key))
    .filter(key => content?.[key] !== undefined)
    .map(key => [key, content[key]]));
}

// Plain content only: reject coercion, unknown keys, operator keys and unsafe links before MongoDB.
export function validateContentPatch(patch) {
  const check = (value, template, key) => {
    if (Array.isArray(template)) {
      if (!Array.isArray(value) || value.length > 200) return `${key} must be a list with at most 200 entries.`;
      for (const entry of value) {
        const problem = check(entry, template[0], key);
        if (problem) return problem;
      }
    } else if (template && typeof template === 'object') {
      if (!value || typeof value !== 'object' || Array.isArray(value)) return `${key} must be an object.`;
      for (const [field, entry] of Object.entries(value)) {
        if (!Object.hasOwn(template, field)) return `${key}.${field} is not editable.`;
        const problem = check(entry, template[field], `${key}.${field}`);
        if (problem) return problem;
      }
    } else {
      if (typeof value !== typeof template) return `${key} has an invalid value type.`;
      if (typeof value === 'number' && !Number.isFinite(value)) return `${key} must be a finite number.`;
      if (typeof value === 'string') {
        if (value.length > 12000) return `${key} is too long.`;
        const field = key.split('.').at(-1);
        if ((['href','route','url','image','img','introImage','heroImage','videoUrl'].includes(field) || /^image_\d+$/.test(field)) && value) {
          if (!/^\/(?!\/)/.test(value)) {
            try {
              const url = new URL(value);
              if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password) return `${key} requires a local path or an HTTP URL.`;
            } catch { return `${key} requires a local path or an HTTP URL.`; }
          }
        }
        if (['opens','closes'].includes(field) && !/^([01]\d|2[0-3]):[0-5]\d$/.test(value)) return `${key} must use HH:MM.`;
        if (field === 'days' && !['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'].includes(value)) return `${key} contains an invalid weekday.`;
        if (field === 'slug' && !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value)) return `${key} must use lowercase letters, numbers and hyphens.`;
      }
    }
    return null;
  };
  return check(patch, DEFAULT_WEBSITE_CONTENT, 'content');
}

export function flattenContentPatch(patch, prefix = '') {
  return Object.fromEntries(Object.entries(patch).flatMap(([key, value]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    return value && typeof value === 'object' && !Array.isArray(value)
      ? Object.entries(flattenContentPatch(value, name)) : [[name, value]];
  }));
}
